/**
 * Builds the academic year the school is living in right now: Semester 1
 * finished and marked, Semester 2 about half taught.
 *
 * The point of this seed is that the two halves must look genuinely different.
 * A finished semester has every mark in, a rank on every report card and no
 * loose ends. A semester still running has a register that stops at today, work
 * that has been set but not yet handed in, subjects whose teacher is behind on
 * marking, and a final examination that exists only as a date. Filling both to
 * the brim would make the system impossible to demonstrate, because every
 * screen that distinguishes "not yet" from "nothing" would look the same.
 *
 * Nothing here is invented independently of anything else. A mark belongs to an
 * assessment, which belongs to a class-subject taught by a named teacher in a
 * term of this year; a submission belongs to an assignment set for that same
 * class and subject; attendance belongs to the enrolment that puts the pupil in
 * that class. Rows are generated by walking those relationships, never by
 * picking identifiers at random.
 */

export const YEAR_NAME = '2025 - 2026';

/**
 * Written to `students.notes` on every pupil this seed invents.
 *
 * The seed has to be able to tell its own generated intake from the real
 * children on the roster, because a re-run must remove the pupils it created
 * last time and must never touch anyone else. Recognising them by their code or
 * their enrolment date would eventually catch a real pupil; an explicit marker
 * cannot.
 */
